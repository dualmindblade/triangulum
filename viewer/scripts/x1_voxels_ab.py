#!/usr/bin/env python3
"""X-1 (B-19): A/B the SAME altitude-ladder pose with the voxel near-field on
and off (`voxels on|off`, the toggle sync_diff.py uses; documented
byte-identical round trip).

If the 0.5-1 km staircase is a property of ALTITUDE, turning the voxel patch
off at 0.3 km should leave the boundary healthy. If it is a property of WHICH
RENDERER draws that ground, the 0.3 km frame should acquire the same lattice
the 1 km frame has, with the camera, light, terrain and boundary field
untouched.

Usage (from viewer/): python scripts/x1_voxels_ab.py [--tag voxab]
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import altitude_ladder as al  # noqa: E402

VIEWER = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="lake_shore,river_bank,snowline,ecotone")
    ap.add_argument("--alts", default="0.3,0.5,0.7,1.0")
    ap.add_argument("--size", default="1280x720")
    ap.add_argument("--tag", default="voxab")
    args = ap.parse_args()

    want = [s.strip() for s in args.only.split(",")]
    sites = [s for s in al.SITES if s[0] in want]
    alts = [float(a) for a in args.alts.split(",")]
    w, h = (int(x) for x in args.size.split("x"))

    truth = al.probe_pass(VIEWER, sites, alts)

    lines = ["# generated by x1_voxels_ab.py", "mode fly",
             "weather pin 0.10 0.0", "weather time 0", "weather season 0.45"]
    for site in sites:
        name, _, tlat, tlon, _, _, _ = site
        t = truth[name]
        target_pos = al.unit(tlat, tlon) * (al.R_KM + t["aim_km"])
        sun_lat = max(-23.0, min(23.0, tlat))
        sun_lon = tlon - 15.0
        for alt in alts:
            rtag = al.rung_tag(alt)
            clat, clon, _ = al.rung_geometry(site, alt)
            cam = al.unit(clat, clon) * (al.R_KM + t["cam_ground_km"][rtag] + alt)
            yaw, pitch = al.aim(cam, target_pos)
            pitch = max(-al.PITCH_LIMIT_DEG, min(al.PITCH_LIMIT_DEG, pitch))
            lines += [f"teleport {clat:.6f} {clon:.6f} {alt}",
                      f"look {yaw:.5f} {pitch:.5f}",
                      f"sun {sun_lat:.2f} {sun_lon:.2f}",
                      "voxels on", f"shot {name}_{rtag}_on",
                      "voxels off", f"shot {name}_{rtag}_off",
                      "voxels on"]
    script = VIEWER / "scripts" / f"_x1-{args.tag}.play"
    script.write_text("\n".join(lines) + "\n", encoding="utf-8")

    exe = VIEWER / "target" / "release" / "examples" / "play.exe"
    r = subprocess.run([str(exe), str(script), "--size", args.size],
                       cwd=VIEWER, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
        raise SystemExit(f"play failed ({r.returncode})")
    run_dir = VIEWER / "interchange" / "runs" / script.stem

    rows = []
    for site in sites:
        name, _, _, _, _, mask_kind, _ = site
        for alt in alts:
            rtag = al.rung_tag(alt)
            _, cross_km, down_km = al.frame_scale(alt, h)
            rec = {"site": name, "alt_km": alt}
            for arm in ("on", "off"):
                im = np.asarray(Image.open(run_dir / f"{name}_{rtag}_{arm}.png")
                                .convert("RGB")).astype(np.int16)
                lint = al.lint_staircase(al.class_mask(im, mask_kind),
                                         cross_km, down_km)
                rec[arm] = {k: lint.get(k) for k in
                            ("status", "jumpiness", "step_px", "step_m",
                             "step_voxels", "staircase")}
            rows.append(rec)
            a, b = rec["on"], rec["off"]
            print(f"{name:<12}{alt:>6} km   voxels-on step_m={str(a.get('step_m')):>8}"
                  f"   voxels-off step_m={str(b.get('step_m')):>8}"
                  f"   ratio={(b['step_m']/a['step_m']):.2f}"
                  if a.get("step_m") and b.get("step_m") else f"{name} {alt} incomplete")

    out = VIEWER / "interchange" / "altitude-ladder" / f"x1-{args.tag}.json"
    out.write_text(json.dumps(rows, indent=1), encoding="utf-8")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
