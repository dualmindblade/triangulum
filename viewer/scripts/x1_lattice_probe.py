#!/usr/bin/env python3
"""X-1 (B-19) diagnostic driver: is the 0.5-1 km staircase pitch owned by the
MESH VERTEX LATTICE, or by something world-anchored?

It reuses `altitude_ladder.py` wholesale — same sites, same 55 deg framing,
same `lint_staircase` — and only varies things the ladder holds fixed:

  --patch S   voxel patch scale (play.exe --patch, clamped 0.3..2.0). Moves
              the voxel/mesh handoff radius WITHOUT moving the camera, the
              light, the terrain, or the boundary field.
  --alts      arbitrary altitude list.

Two predictions the model makes (voxel patch radius
`r_m = (200 + (2.5 - alt_km) * 120) * patch`, aim point at
`alt_km * 1000 / tan(55 deg)` metres downrange):

  * at 0.3 km, patch 1.0 keeps the aim point INSIDE the patch (464 m vs
    210 m) and patch 0.3 puts it OUTSIDE (139 m vs 210 m)  -> the healthy
    frame should acquire the staircase.
  * at 1.0 km, patch 1.0 leaves it OUTSIDE (380 m vs 700 m) and patch 2.0
    brings it back INSIDE (760 m vs 700 m) -> the staircase should retreat.

Usage (from viewer/):
  python scripts/x1_lattice_probe.py --tag patch --patches 0.3,1.0,2.0 \
      --alts 0.3,0.5,1.0 --only lake_shore,river_bank,snowline,ecotone
"""

import argparse
import json
import math
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import altitude_ladder as al  # noqa: E402

VIEWER = Path(__file__).resolve().parent.parent


def voxel_patch_radius_m(alt_km: float, patch: float) -> float:
    """renderer.rs:1820 — the near-field voxel disc radius."""
    return (200.0 + max(0.0, 2.5 - alt_km) * 120.0) * patch


def aim_offset_m(alt_km: float) -> float:
    """Ladder geometry: horizontal camera->target distance at 55 deg."""
    return alt_km * 1000.0 / math.tan(math.radians(al.DEPRESSION_DEG))


def mesh_vertex_spacing_m(level: int) -> float:
    """terrain.rs: tile size = (pi/2 * R) / 2^level, 32 quads across."""
    return (math.pi / 2.0 * al.R_KM) / ((1 << level) * al.__dict__.get("TILE_QUADS", 32)) * 1000.0


def run_play(script: Path, size: str, extra: list[str]) -> Path:
    exe = VIEWER / "target" / "release" / "examples" / "play.exe"
    cmd = [str(exe), str(script), "--size", size] + extra
    r = subprocess.run(cmd, cwd=VIEWER, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
        raise SystemExit(f"play failed ({r.returncode}) on {script.name}")
    return VIEWER / "interchange" / "runs" / script.stem


def render(sites, alts, truth, patch: float, tag: str, size: str):
    lines = ["# generated by x1_lattice_probe.py", "mode fly",
             "weather pin 0.10 0.0", "weather time 0", "weather season 0.45"]
    poses = {}
    for site in sites:
        name, _, tlat, tlon, _, _, _ = site
        t = truth[name]
        target_pos = al.unit(tlat, tlon) * (al.R_KM + t["aim_km"])
        sun_lat = max(-23.0, min(23.0, tlat))
        sun_lon = tlon - 15.0
        for alt in alts:
            rtag = al.rung_tag(alt)
            clat, clon, d = al.rung_geometry(site, alt)
            cam_pos = al.unit(clat, clon) * (al.R_KM + t["cam_ground_km"][rtag] + alt)
            yaw, pitch = al.aim(cam_pos, target_pos)
            pitch = max(-al.PITCH_LIMIT_DEG, min(al.PITCH_LIMIT_DEG, pitch))
            poses[(name, alt)] = {"yaw": yaw, "pitch": pitch, "offset_km": d}
            lines += [
                f"teleport {clat:.6f} {clon:.6f} {alt}",
                f"look {yaw:.5f} {pitch:.5f}",
                f"sun {sun_lat:.2f} {sun_lon:.2f}",
                f"shot {name}_{rtag}",
            ]
    script = VIEWER / "scripts" / f"_x1-{tag}.play"
    script.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return run_play(script, size, ["--patch", f"{patch:g}"]), poses


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="lake_shore,river_bank,snowline,ecotone")
    ap.add_argument("--alts", default="0.3,0.5,1.0")
    ap.add_argument("--patches", default="1.0")
    ap.add_argument("--tag", default="probe")
    ap.add_argument("--size", default="1280x720")
    args = ap.parse_args()

    want = [s.strip() for s in args.only.split(",") if s.strip()]
    sites = [s for s in al.SITES if s[0] in want]
    alts = [float(a) for a in args.alts.split(",")]
    patches = [float(p) for p in args.patches.split(",")]
    w, h = (int(x) for x in args.size.split("x"))

    truth = al.probe_pass(VIEWER, sites, alts)

    rows = []
    for patch in patches:
        tag = f"{args.tag}-p{patch:g}".replace(".", "")
        run_dir, poses = render(sites, alts, truth, patch, tag, args.size)
        for site in sites:
            name, _, _, _, _, mask_kind, _ = site
            for alt in alts:
                rtag = al.rung_tag(alt)
                png = run_dir / f"{name}_{rtag}.png"
                im = np.asarray(Image.open(png).convert("RGB")).astype(np.int16)
                mask = al.class_mask(im, mask_kind)
                _, cross_km, down_km = al.frame_scale(alt, h)
                lint = al.lint_staircase(mask, cross_km, down_km)
                r_m = voxel_patch_radius_m(alt, patch)
                off_m = aim_offset_m(alt)
                rows.append({
                    "site": name, "alt_km": alt, "patch": patch,
                    "patch_radius_m": round(r_m, 1),
                    "aim_offset_m": round(off_m, 1),
                    "aim_inside_patch": bool(off_m < r_m),
                    "png": str(png.relative_to(VIEWER)),
                    **{k: lint.get(k) for k in
                       ("status", "jumpiness", "step_px", "step_m",
                        "step_voxels", "slope_px", "gate_applies", "staircase")},
                })

    out = VIEWER / "interchange" / "altitude-ladder" / f"x1-{args.tag}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(rows, indent=1), encoding="utf-8")

    hdr = f"{'site':<12}{'alt':>6}{'patch':>7}{'r_m':>8}{'off_m':>8}{'in?':>5}" \
          f"{'step_m':>9}{'jumpy':>8}{'stair':>7}"
    print(hdr)
    print("-" * len(hdr))
    for r in rows:
        print(f"{r['site']:<12}{r['alt_km']:>6}{r['patch']:>7}"
              f"{r['patch_radius_m']:>8}{r['aim_offset_m']:>8}"
              f"{'Y' if r['aim_inside_patch'] else 'n':>5}"
              f"{str(r.get('step_m')):>9}{str(r.get('jumpiness')):>8}"
              f"{str(r.get('staircase')):>7}")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
