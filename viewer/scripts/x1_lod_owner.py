#!/usr/bin/env python3
"""X-1 (B-19): who OWNS the pixels a boundary is drawn on?

Renders altitude-ladder poses with `TRI_LOD_RING_DEBUG=1`, whose fragment
shader returns `0.20 + 0.75 * fract(vec3(0.37,0.61,0.83) * band)` with
`band = level + 1` for heightfield tiles and `band = 0.5` for voxel chunks
(renderer.rs:3439). Inverting that palette gives, per pixel, the exact
renderer + LOD level that drew it — so "the boundary at 1 km is drawn by a
level-14 mesh tile, and at 0.3 km by voxel chunks" becomes a measurement.

Usage (from viewer/):
  python scripts/x1_lod_owner.py --only river_bank,lake_shore --alts 0.3,1.0
"""

import argparse
import json
import math
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import altitude_ladder as al  # noqa: E402

VIEWER = Path(__file__).resolve().parent.parent
TILE_QUADS = 32


def band_color(band: float) -> np.ndarray:
    v = np.array([0.37, 0.61, 0.83]) * band
    return 0.20 + 0.75 * (v - np.floor(v))


def srgb_encode(c: np.ndarray) -> np.ndarray:
    """wgpu Bgra8UnormSrgb target: the shader writes linear, the surface
    encodes. Match the encode so the palette inversion works on PNG bytes."""
    lo = c * 12.92
    hi = 1.055 * np.power(np.clip(c, 1e-6, 1.0), 1.0 / 2.4) - 0.055
    return np.where(c <= 0.0031308, lo, hi)


def vertex_spacing_m(level: int) -> float:
    return (math.pi / 2.0 * al.R_KM) / ((1 << level) * TILE_QUADS) * 1000.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="river_bank,lake_shore,snowline,ecotone")
    ap.add_argument("--alts", default="0.3,0.5,0.7,1.0")
    ap.add_argument("--size", default="1280x720")
    ap.add_argument("--tag", default="lod")
    args = ap.parse_args()

    want = [s.strip() for s in args.only.split(",")]
    sites = [s for s in al.SITES if s[0] in want]
    alts = [float(a) for a in args.alts.split(",")]
    w, h = (int(x) for x in args.size.split("x"))

    truth = al.probe_pass(VIEWER, sites, alts)

    lines = ["# generated by x1_lod_owner.py", "mode fly",
             "weather pin 0.10 0.0", "weather time 0", "weather season 0.45"]
    for site in sites:
        name, _, tlat, tlon, _, _, _ = site
        t = truth[name]
        target_pos = al.unit(tlat, tlon) * (al.R_KM + t["aim_km"])
        for alt in alts:
            rtag = al.rung_tag(alt)
            clat, clon, _ = al.rung_geometry(site, alt)
            cam = al.unit(clat, clon) * (al.R_KM + t["cam_ground_km"][rtag] + alt)
            yaw, pitch = al.aim(cam, target_pos)
            pitch = max(-al.PITCH_LIMIT_DEG, min(al.PITCH_LIMIT_DEG, pitch))
            lines += [f"teleport {clat:.6f} {clon:.6f} {alt}",
                      f"look {yaw:.5f} {pitch:.5f}",
                      f"shot {name}_{rtag}"]
    script = VIEWER / "scripts" / f"_x1-{args.tag}.play"
    script.write_text("\n".join(lines) + "\n", encoding="utf-8")

    env = dict(os.environ, TRI_LOD_RING_DEBUG="1")
    exe = VIEWER / "target" / "release" / "examples" / "play.exe"
    r = subprocess.run([str(exe), str(script), "--size", args.size],
                       cwd=VIEWER, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
        raise SystemExit(f"play failed ({r.returncode})")
    run_dir = VIEWER / "interchange" / "runs" / script.stem

    # palette: voxel chunk (band 0.5) plus every plausible tile level
    bands = {"chunk": 0.5}
    for lvl in range(4, 18):
        bands[f"L{lvl}"] = lvl + 1.0
    names = list(bands)
    pal = np.array([srgb_encode(band_color(bands[n])) * 255.0 for n in names])

    rows = []
    for site in sites:
        name = site[0]
        for alt in alts:
            rtag = al.rung_tag(alt)
            im = np.asarray(Image.open(run_dir / f"{name}_{rtag}.png")
                            .convert("RGB")).astype(float)
            d = np.linalg.norm(im[:, :, None, :] - pal[None, None, :, :], axis=3)
            idx = np.argmin(d, axis=2)
            resid = np.min(d, axis=2)
            good = resid < 6.0
            centre = idx[h // 2, w // 2] if good[h // 2, w // 2] else -1
            counts = {}
            for i, n in enumerate(names):
                c = int(((idx == i) & good).sum())
                if c > 0.002 * w * h:
                    counts[n] = round(c / (w * h), 4)
            rows.append({
                "site": name, "alt_km": alt,
                "centre_owner": names[centre] if centre >= 0 else "unmatched",
                "unmatched_frac": round(float((~good).mean()), 4),
                "composition": counts,
                "png": str((run_dir / f"{name}_{rtag}.png").relative_to(VIEWER)),
            })
            print(f"{name:<12}{alt:>6} km  centre={rows[-1]['centre_owner']:<8}"
                  f" comp={counts}  unmatched={rows[-1]['unmatched_frac']}")

    out = VIEWER / "interchange" / "altitude-ladder" / f"x1-{args.tag}.json"
    out.write_text(json.dumps({
        "vertex_spacing_m": {f"L{l}": round(vertex_spacing_m(l), 2)
                             for l in range(10, 18)},
        "rows": rows}, indent=1), encoding="utf-8")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
